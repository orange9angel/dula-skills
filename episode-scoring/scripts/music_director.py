"""
MusicDirector for the episode-scoring skill.

Analyzes script.story semantics and produces a music cue timeline:
  - Detects emotional arc from dialogue, scene tags and character actions.
  - Decides when BGM should play / stop / fade.
  - Maps each segment to a mood keyword (e.g. cheerful, tense, sad).
  - Writes a `music_cues.json` manifest that dula-engine/tools/generate_audio.py
    can consume directly.

The director never blocks the pipeline: if no suitable music file exists, it
falls back to a procedural placeholder generated by generate_music.py.
"""

